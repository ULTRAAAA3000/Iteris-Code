const dateAttr = (d: string): string => d.split(".").reverse().join("-");

/** HTML сторінки. Хлібні крихти передає pages.ts (так само, як для «Підтримки»), щоб не було циклічних імпортів */
export function newsHtml(crumbs: string): string {
  const soon = SOON.map((s, i) => `<li class="nw-card" style="--i:${i}">
      <img class="nw-hero" src="${idolSrc(s.hero)}" width="72" height="72" alt="" loading="lazy" decoding="async">
      <div><h3>${esc(s.title)} <span class="nw-tag">Скоро</span></h3><p>${esc(s.text)}</p></div>
    </li>`).join("");
  const rel = RELEASES.map((r, i) => `<article class="nw-rel" style="--i:${i}">
      <h3><time datetime="${dateAttr(r.date)}">${esc(r.date)}</time></h3>
      <ul>${r.items.map((x) => `<li>${esc(x)}</li>`).join("")}</ul>
    </article>`).join("");
  return `
  ${crumbs}
  <h1 class="lp-h1">Що нового і що скоро</h1>
  <p class="section-sub">Платформа росте частинами: нові можливості з'являються по кілька разів на тиждень. Тут усе, що вже випущено, і що ми готуємо далі.</p>
  <section class="nw-soon" aria-labelledby="soon">
    <h2 class="section-title" id="soon">Скоро</h2>
    <ul class="nw-cards">${soon}</ul>
    <p class="lp-note">Це плани, а не обіцянки з датами: порядок і склад можуть змінитися. Є думка, що додати першим? <a href="/contact">Напишіть нам</a>.</p>
  </section>
  <section class="nw-log" aria-labelledby="done">
    <h2 class="section-title" id="done">Уже випущено</h2>
    <div class="nw-rels">${rel}</div>
  </section>`;
}
