let n = 0;
export const GO_CHAPTERS = CHAPTERS.map((c) => {
  const from = n + 1;
  n += c.lessons.length;
  return { id: c.id, name: c.name, from, to: n, lessons: c.lessons.map((l, i) => ({ n: from + i, ...l })) };
});
export const GO_OUTLINE = GO_CHAPTERS.flatMap((c) => c.lessons.map((l) => ({ ...l, ch: c.name })));
