// Тег для блоків коду Bash у файлах уроків: працює як String.raw, але дозволяє писати ${…} і зворотні апострофи.
// У звичайному String.raw запис ${var} JavaScript сприйняв би за підстановку, тому в шаблоні пишіть \${var} і \` (зворотний слеш зникне).
export const sh = (s) => s.raw.join("").replace(/\\\$\{/g, "${").replace(/\\`/g, "`");
